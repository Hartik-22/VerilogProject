

`timescale 1ns / 1ps

module tb_evm;

//////////////////////////////////////////////////////
// INPUTS
//////////////////////////////////////////////////////

reg clk;
reg reset;

reg enter_button;
reg [15:0] entered_id;

reg bjp_button;
reg inc_button;
reg aap_button;
reg sp_button;

reg [15:0] admin_password;
reg admin_valid;
reg admin_logout;

//////////////////////////////////////////////////////
// OUTPUTS
//////////////////////////////////////////////////////

wire [15:0] BJP_votes;
wire [15:0] INC_votes;
wire [15:0] AAP_votes;
wire [15:0] SP_votes;

//////////////////////////////////////////////////////
// DUT
//////////////////////////////////////////////////////

evm_top DUT (

    .clk(clk),
    .reset(reset),

    .enter_button(enter_button),
    .entered_id(entered_id),

    .bjp_button(bjp_button),
    .inc_button(inc_button),
    .aap_button(aap_button),
    .sp_button(sp_button),

    .admin_password(admin_password),
    .admin_valid(admin_valid),
    .admin_logout(admin_logout),

    .BJP_votes(BJP_votes),
    .INC_votes(INC_votes),
    .AAP_votes(AAP_votes),
    .SP_votes(SP_votes)
);

//////////////////////////////////////////////////////
// CLOCK GENERATION
//////////////////////////////////////////////////////

always #5 clk = ~clk;

//////////////////////////////////////////////////////
// TASK : CAST VOTE
//////////////////////////////////////////////////////

task cast_vote;

    input [15:0] voterid;
    input [1:0] party;

    begin

        //////////////////////////////////////////////
        // CLEAR BUTTONS
        //////////////////////////////////////////////

        bjp_button = 0;
        inc_button = 0;
        aap_button = 0;
        sp_button  = 0;

        //////////////////////////////////////////////
        // ENTER VOTER ID
        //////////////////////////////////////////////

        entered_id = voterid;
        enter_button = 1;

        #10;

        enter_button = 0;

        //////////////////////////////////////////////
        // WAIT FOR AUTHENTICATION
        //////////////////////////////////////////////

        #30;

        //////////////////////////////////////////////
        // PRESS PARTY BUTTON
        //////////////////////////////////////////////

        case(party)

            //////////////////////////////////////////////////
            // BJP
            //////////////////////////////////////////////////

            2'b00:
            begin
                bjp_button = 1;

                #10;

                bjp_button = 0;
            end

            //////////////////////////////////////////////////
            // INC
            //////////////////////////////////////////////////

            2'b01:
            begin
                inc_button = 1;

                #10;

                inc_button = 0;
            end

            //////////////////////////////////////////////////
            // AAP
            //////////////////////////////////////////////////

            2'b10:
            begin
                aap_button = 1;

                #10;

                aap_button = 0;
            end

            //////////////////////////////////////////////////
            // SP
            //////////////////////////////////////////////////

            2'b11:
            begin
                sp_button = 1;

                #10;

                sp_button = 0;
            end

        endcase

        //////////////////////////////////////////////
        // WAIT BEFORE NEXT USER
        //////////////////////////////////////////////

        #80;

    end

endtask

//////////////////////////////////////////////////////
// TEST SEQUENCE
//////////////////////////////////////////////////////

initial begin

    //////////////////////////////////////////////
    // INITIALIZE
    //////////////////////////////////////////////

    clk = 0;
    reset = 1;

    enter_button = 0;

    bjp_button = 0;
    inc_button = 0;
    aap_button = 0;
    sp_button = 0;

    admin_password = 0;
    admin_valid = 0;
    admin_logout = 0;

    entered_id = 0;

    //////////////////////////////////////////////
    // RESET
    //////////////////////////////////////////////

    #20;
    reset = 0;

    //////////////////////////////////////////////
    // BJP = 4 VOTES
    //////////////////////////////////////////////

    cast_vote(16'd1021, 2'b00);
    cast_vote(16'd2045, 2'b00);
    cast_vote(16'd3098, 2'b00);
    cast_vote(16'd4112, 2'b00);

    //////////////////////////////////////////////
    // INC = 2 VOTES
    //////////////////////////////////////////////

    cast_vote(16'd5234, 2'b01);
    cast_vote(16'd6345, 2'b01);

    //////////////////////////////////////////////
    // AAP = 2 VOTES
    //////////////////////////////////////////////

    cast_vote(16'd7456, 2'b10);
    cast_vote(16'd8567, 2'b10);

    //////////////////////////////////////////////
    // SP = 2 VOTES
    //////////////////////////////////////////////

    cast_vote(16'd9123, 2'b11);
    cast_vote(16'd9999, 2'b11);

    //////////////////////////////////////////////
    // INVALID USER
    //////////////////////////////////////////////

    cast_vote(16'd5555, 2'b00);

    //////////////////////////////////////////////
    // ADMIN LOGIN
    //////////////////////////////////////////////

    #100;

    admin_password = 16'd1234;
    admin_valid = 1;

    #20;

    admin_valid = 0;

    //////////////////////////////////////////////
    // WAIT
    //////////////////////////////////////////////

    #200;

    $finish;

end

endmodule